const chipRow = document.getElementById('chip-row');
const panel = document.getElementById('niche-panel');
if (chipRow && panel) {
  NICHES.forEach((n, i) => {
    const b = document.createElement('button');
    b.className = 'chip'; b.type = 'button'; b.textContent = n.name;
    b.setAttribute('aria-expanded', 'false');
    b.addEventListener('click', () => {
      const wasOn = b.classList.contains('on');
      chipRow.querySelectorAll('.chip').forEach(c => { c.classList.remove('on'); c.setAttribute('aria-expanded','false'); });
      if (wasOn) { panel.hidden = true; return; }
      b.classList.add('on'); b.setAttribute('aria-expanded','true');
      panel.hidden = false;
      panel.innerHTML = n.rows.map(r =>
        `<div class="np-row"><span class="np-name">${r[0]}</span><span class="np-what">${r[1]}</span><span class="np-cost">${r[2]}</span></div>`
      ).join('') +
      `<div class="np-cta"><a class="btn btn-wa" href="https://wa.me/79164154116?text=${encodeURIComponent(n.wa)}">Обсудить в WhatsApp</a></div>`;
      panel.getAnimations?.().forEach(a => { a.cancel(); a.play(); });
    });
    chipRow.appendChild(b);
  });
}

// Reveal при скролле.
const reduced = matchMedia('(prefers-reduced-motion: reduce)').matches;
if (reduced || !('IntersectionObserver' in window)) {
  document.querySelectorAll('[data-reveal]').forEach(el => el.classList.add('in'));
} else {
  const io = new IntersectionObserver(entries => {
    for (const e of entries) if (e.isIntersecting) { e.target.classList.add('in'); io.unobserve(e.target); }
  }, { rootMargin: '0px 0px -8% 0px', threshold: .1 });
  document.querySelectorAll('[data-reveal]').forEach(el => io.observe(el));
}
